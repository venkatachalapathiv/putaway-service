package com.company.wms.putaway.mapper;

import com.company.wms.putaway.domain.PutAwayTask;
import com.company.wms.putaway.domain.PutAwayTaskStatus;
import com.company.wms.putaway.dto.CreatePutAwayTaskRequest;
import com.company.wms.putaway.dto.PutAwayTaskResponse;
import org.springframework.stereotype.Component;

@Component
public class PutAwayTaskMapper {

    
     //Entity → Response DTO.
     
    public PutAwayTaskResponse toResponse(PutAwayTask entity) {
        if (entity == null) {
            return null;
        }
        return new PutAwayTaskResponse(
                entity.getId(),
                entity.getTaskNumber(),
                entity.getGoodsReceiptLineId(),
                entity.getSkuId(),
                entity.getQuantity(),
                entity.getTargetBinId(),
                entity.getStatus() != null ? entity.getStatus().name() : null,
                entity.getAssignedTo(),
                entity.getCreatedAt(),
                entity.getCompletedAt()
        );
    }

    
     // Request DTO → new Entity (status = CREATED, no id yet).
     // Task number is generated by the service, not here.
     
    public PutAwayTask toEntity(CreatePutAwayTaskRequest request) {
        if (request == null) {
            return null;
        }
        PutAwayTask task = new PutAwayTask();
        task.setGoodsReceiptLineId(request.getGoodsReceiptLineId());
        task.setSkuId(request.getSkuId());
        task.setQuantity(request.getQuantity());
        task.setTargetBinId(request.getTargetBinId());
        task.setWarehouseId(request.getWarehouseId());
        task.setAssignedTo(request.getAssignedTo());
        task.setStatus(PutAwayTaskStatus.CREATED);
        return task;
    }
}